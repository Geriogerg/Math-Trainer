// Regenerates `test/domain/determinism/determinism_references.dart` on the
// Dart VM — the platform the server will replay on (Phase 2).
//
//   dart run tool/determinism_references.dart
//
// Run it only on purpose: when a change is MEANT to alter sequences or level
// updates (e.g. removing the useless `nextInt(1)` draw, or levels in
// hundredths). The diff of the references file is then the evidence of what
// changed; review it in the same commit. Never run it to make a failing
// JavaScript run pass — that would hide exactly the bug the test exists for.

import 'dart:io';

import '../test/domain/determinism/determinism_cases.dart';

void main() {
  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/determinism_references.dart on the Dart VM.',
    )
    ..writeln('// Do not edit; see that tool for when to regenerate.')
    ..writeln()
    ..writeln('const sessionSequenceReferences = <String, String>{');
  for (final setup in determinismSetups) {
    for (final seed in determinismSeeds) {
      out.writeln(
        "  ${_quote('${setup.name} | $seed')}: ${_quote(sessionSequence(seed, setup))},",
      );
    }
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('const endlessSequenceReferences = <int, String>{');
  for (final seed in determinismSeeds) {
    out.writeln('  $seed: ${_quote(endlessSequence(seed))},');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('const placementSequenceReferences = <String, String>{');
  for (final pattern in placementPatterns.keys) {
    for (final seed in determinismSeeds) {
      out.writeln(
        "  ${_quote('$pattern | $seed')}: ${_quote(placementSequence(seed, pattern))},",
      );
    }
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('const levelUpdateGridReference = ${_quote(levelUpdateGrid())};');
  const path = 'test/domain/determinism/determinism_references.dart';
  File(path).writeAsStringSync(out.toString());
  // CI checks formatting: format here so a regeneration is diff-clean.
  final format = Process.runSync('dart', ['format', path], runInShell: true);
  if (format.exitCode != 0) throw StateError('dart format: ${format.stderr}');
  stdout.writeln('wrote $path');
}

/// Single-quoted Dart literal; the strings hold only digits, letters,
/// spaces and `|:;,-()`, never quotes or `$`.
String _quote(String s) {
  if (s.contains("'") || s.contains(r'$') || s.contains(r'\')) {
    throw ArgumentError.value(s, 's', 'unexpected character');
  }
  return "'$s'";
}
