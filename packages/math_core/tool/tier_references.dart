// Regenerates `test/tiers/tier_references.dart` on the Dart VM: rules v2's
// pinned question sequences (`doc/levels.md`).
//
//   dart run tool/tier_references.dart
//
// Only for a change MEANT to alter rules v2's questions; never to make a
// JavaScript run pass (same rule as `tool/determinism_references.dart`).

import 'dart:io';

import 'package:math_core/models/exercise_type.dart';

import '../test/tiers/tier_cases.dart';

void main() {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/tier_references.dart on the Dart VM.')
    ..writeln('// Do not edit; see that tool for when to regenerate.')
    ..writeln()
    ..writeln('const tierSequenceReferences = <String, String>{');
  for (final type in ExerciseType.values) {
    for (final seed in tierSeeds) {
      out.writeln(
        "  ${_quote('${type.name} | $seed')}: ${_quote(tierSequence(type, seed))},",
      );
    }
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('const gameSequenceReferences = <int, String>{');
  for (final seed in tierSeeds) {
    out.writeln('  $seed: ${_quote(gameSequence(seed))},');
  }
  out.writeln('};');
  File('test/tiers/tier_references.dart').writeAsStringSync(out.toString());
}

String _quote(String s) =>
    "'${s.replaceAll(r'\', r'\').replaceAll("'", r"\'")}'";
