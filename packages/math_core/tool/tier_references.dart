// Regenerates `test/tiers/tier_references.dart` (rules v2),
// `test/tiers/tier_references_v4.dart` (rules v4),
// `test/tiers/tier_references_v5.dart` (rules v5) and
// `test/tiers/tier_references_v6.dart` (rules v6) and
// `test/tiers/tier_references_v9.dart` (rules v9) on the Dart VM: the
// pinned question sequences (`doc/levels.md` sections 5 and 5b). A run
// that changes an older version's file is a bug: those versions are
// frozen.
//
//   dart run tool/tier_references.dart
//
// Only for a change MEANT to alter a version's questions — which, once
// that version is played, is a new version instead; never to make a
// JavaScript run pass (same rule as `tool/determinism_references.dart`).

import 'dart:io';

import 'package:math_core/leveling/rules_version.dart';
import 'package:math_core/models/exercise_type.dart';

import '../test/tiers/tier_cases.dart';

void main() {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/tier_references.dart on the Dart VM.')
    ..writeln('// Do not edit; see that tool for when to regenerate.')
    ..writeln()
    ..writeln('const tierSequenceReferences = <String, String>{');
  for (final type in ExerciseType.values) {
    for (final seed in tierSeeds) {
      out.writeln(
        "  ${_quote('${type.name} | $seed')}: ${_quote(tierSequence(type, seed))},",
      );
    }
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('const gameSequenceReferences = <int, String>{');
  for (final seed in tierSeeds) {
    out.writeln('  $seed: ${_quote(gameSequence(seed))},');
  }
  out.writeln('};');
  File('test/tiers/tier_references.dart').writeAsStringSync(out.toString());

  // Rules v4 (pattern questions, long addition and subtraction): its own
  // file, so regenerating it never touches v2's.
  final v4 = StringBuffer()
    ..writeln('// GENERATED by tool/tier_references.dart on the Dart VM.')
    ..writeln('// Do not edit; see that tool for when to regenerate.')
    ..writeln()
    ..writeln('const patternedSequenceReferences = <String, String>{');
  for (final type in ExerciseType.values) {
    for (final seed in tierSeeds) {
      v4.writeln(
        "  ${_quote('${type.name} | $seed')}: "
        "${_quote(patternedSequence(type, seed))},",
      );
    }
  }
  v4
    ..writeln('};')
    ..writeln()
    ..writeln('const familySequenceReferences = <int, String>{');
  for (final seed in tierSeeds) {
    v4.writeln('  $seed: ${_quote(familySequence(seed))},');
  }
  v4
    ..writeln('};')
    ..writeln()
    ..writeln('const gameSequenceV4References = <int, String>{');
  for (final seed in tierSeeds) {
    v4.writeln('  $seed: ${_quote(gameSequence(seed, RulesVersion.v4))},');
  }
  v4.writeln('};');
  File('test/tiers/tier_references_v4.dart').writeAsStringSync(v4.toString());

  // Rules v5 (pattern questions sized by tier, no reviews).
  final v5 = StringBuffer()
    ..writeln('// GENERATED by tool/tier_references.dart on the Dart VM.')
    ..writeln('// Do not edit; see that tool for when to regenerate.')
    ..writeln()
    ..writeln('const patternedSequenceV5References = <String, String>{');
  for (final type in ExerciseType.values) {
    for (final seed in tierSeeds) {
      v5.writeln(
        "  ${_quote('${type.name} | $seed')}: "
        "${_quote(patternedSequenceV5(type, seed))},",
      );
    }
  }
  v5
    ..writeln('};')
    ..writeln()
    ..writeln('const familySequenceV5References = <int, String>{');
  for (final seed in tierSeeds) {
    v5.writeln('  $seed: ${_quote(familySequenceV5(seed))},');
  }
  v5
    ..writeln('};')
    ..writeln()
    ..writeln('const gameSequenceV5References = <int, String>{');
  for (final seed in tierSeeds) {
    v5.writeln('  $seed: ${_quote(gameSequence(seed, RulesVersion.v5))},');
  }
  v5.writeln('};');
  File('test/tiers/tier_references_v5.dart').writeAsStringSync(v5.toString());

  // Rules v6 (√ of powers of 2 sized by its own row).
  final v6 = StringBuffer()
    ..writeln('// GENERATED by tool/tier_references.dart on the Dart VM.')
    ..writeln('// Do not edit; see that tool for when to regenerate.')
    ..writeln()
    ..writeln('const patternedSequenceV6References = <String, String>{');
  for (final type in ExerciseType.values) {
    for (final seed in tierSeeds) {
      v6.writeln(
        "  ${_quote('${type.name} | $seed')}: "
        "${_quote(patternedSequenceV6(type, seed))},",
      );
    }
  }
  v6
    ..writeln('};')
    ..writeln()
    ..writeln('const familySequenceV6References = <int, String>{');
  for (final seed in tierSeeds) {
    v6.writeln('  $seed: ${_quote(familySequenceV6(seed))},');
  }
  v6
    ..writeln('};')
    ..writeln()
    ..writeln('const gameSequenceV6References = <int, String>{');
  for (final seed in tierSeeds) {
    v6.writeln('  $seed: ${_quote(gameSequence(seed, RulesVersion.v6))},');
  }
  v6.writeln('};');
  File('test/tiers/tier_references_v6.dart').writeAsStringSync(v6.toString());

  // Rules v9 (`doc/levels.md` v1.6: spaces drawn without repeats).
  final v9 = StringBuffer()
    ..writeln('// GENERATED by tool/tier_references.dart on the Dart VM.')
    ..writeln('// Do not edit; see that tool for when to regenerate.')
    ..writeln()
    ..writeln('const gameSequenceByTierV9References = <String, String>{');
  for (final type in ExerciseType.values) {
    for (final seed in tierSeeds) {
      v9.writeln(
        "  ${_quote('${type.name} | $seed')}: "
        "${_quote(gameSequenceV9(type, seed))},",
