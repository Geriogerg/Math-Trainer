// Writes `test/method/method_pins.dart`: the pinned Methods, one per family
// and per fallback in each tier band (`doc/levels.md` v1.6 section 9), on
// the Dart VM. Regenerate only for a change MEANT to alter what a Method
// says — and read the diff: every line is what a player sees.
//
//   dart run tool/method_pins.dart && dart format test/method

import 'dart:io';

import '../test/method/method_pin_cases.dart';

void main() {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/method_pins.dart on the Dart VM.')
    ..writeln('// Do not edit; see that tool for when to regenerate.')
    ..writeln()
    ..writeln('const methodPins = <String, String>{');
  final pins = methodPinCases();
  for (final key in pins.keys.toList()..sort()) {
    out.writeln('  ${_quote(key)}: ${_quote(pins[key]!)},');
  }
  out.writeln('};');
  File('test/method/method_pins.dart').writeAsStringSync(out.toString());
  print('${pins.length} pins');
}

String _quote(String s) =>
    "'${s.replaceAll(r'\', r'\').replaceAll("'", r"\'").replaceAll('\n', r'\n')}'";
